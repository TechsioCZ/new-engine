#!/usr/bin/env node
/* Re-resolve aliases at scheme boundaries, rather than inheriting computed
 * root snapshots, and export the built-in brands and the token foundation as
 * data for runtime brands. Run with --write after changing token aliases. */
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import postcss from "postcss"

const root = fileURLToPath(new URL("../src/tokens/", import.meta.url))
const output = path.join(root, "_scheme-scopes.css")
const themeDir = fileURLToPath(new URL("../src/theme/", import.meta.url))
const builtInOutput = path.join(themeDir, "built-in-brands.ts")
const foundationOutput = path.join(themeDir, "foundation-tokens.ts")
const brandList = JSON.parse(
  readFileSync(path.join(root, "figma/brands.json"), "utf8")
)
const IMPORT_PATH = /^["'](\.[^"']+)["']/
const DYNAMIC_VALUE = /var\(|light-dark\(/
const aliases = new Map()
const visited = new Set()
function collect(file) {
  if (visited.has(file) || file === output) {
    return
  }
  visited.add(file)
  const css = postcss.parse(readFileSync(file, "utf8"))
  css.each((node) => {
    if (node.type === "atrule" && node.name === "import") {
      const relative = node.params.match(IMPORT_PATH)?.[1]
      if (relative) {
        collect(path.resolve(path.dirname(file), relative))
      }
    }
    if (node.type === "atrule" && node.name === "theme") {
      node.walkDecls((decl) => aliases.set(decl.prop, decl.value))
    }
  })
}
collect(path.join(root, "_tokens-base.css"))
const scopes =
  ":where(:root, .light, .dark, .always-light, .always-dark, .reverse, [data-theme])"
const declarations = (entries, includeLiterals = false) =>
  [...entries]
    .filter(
      ([name, value]) =>
        includeLiterals || corrections.has(name) || DYNAMIC_VALUE.test(value)
    )
    .map(([name, value]) => `    ${name}: ${value};`)
    .join("\n")
const corrections = new Map()
const brandCorrections = new Map()
for (const file of ["_foundation-overrides.css", "_business-atoms.css"]) {
  postcss
    .parse(readFileSync(path.join(root, file), "utf8"))
    .walkDecls((decl) => {
      if (!decl.prop.startsWith("--")) {
        return
      }
      const selector = decl.parent.selector
      if (
        selector?.startsWith("[data-theme=") &&
        decl.parent.parent?.type !== "atrule"
      ) {
        const entries = brandCorrections.get(selector) ?? new Map()
        entries.set(decl.prop, decl.value)
        brandCorrections.set(selector, entries)
      } else if (decl.parent.name === "theme" || selector?.includes(":root")) {
        corrections.set(decl.prop, decl.value)
      }
    })
}
const brands = postcss.parse(
  readFileSync(path.join(root, "figma/brand-overrides.css"), "utf8")
)
// Brand literals must not leak into a different nested brand. Brands are
// open data, so any foundation literal may be overridden: reset every one, and
// only at brand boundaries, not every scheme switch.
const brandLiteralDefaults = new Map(
  [...aliases].filter(([, value]) => !DYNAMIC_VALUE.test(value))
)
let result = `/* Generated by scripts/validate-token-scopes.js --write. Do not hand edit.\n * Aliases resolve per scheme; brand-owned literals reset at brand boundaries. */\n@layer theme {\n  ${scopes} {\n${declarations(aliases)}\n  }\n`
if (brandLiteralDefaults.size > 0) {
  result += `  :where([data-theme]) {\n${declarations(brandLiteralDefaults, true)}\n  }\n`
}
const builtInTokens = new Map()
brands.walkRules((rule) => {
  if (!rule.selector.startsWith("[data-theme=")) {
    return
  }
  const entries = new Map()
  rule.walkDecls((decl) => {
    if (!corrections.has(decl.prop)) {
      entries.set(decl.prop, decl.value)
    }
  })
  for (const [name, value] of brandCorrections.get(rule.selector) ?? []) {
    entries.set(name, value)
  }
  builtInTokens.set(rule.selector, entries)
  // Scope proximity, not distant ancestor selector order, chooses the brand.
  result += `  @scope (${rule.selector}) to ([data-theme]) {\n    :where(:scope, .light, .dark, .always-light, .always-dark, .reverse) {\n${declarations(entries, true)}\n    }\n  }\n`
})
result += "}\n"

const brandSelector = (key) => `[data-theme="${key}"]`
for (const { key } of brandList) {
  if (!builtInTokens.has(brandSelector(key))) {
    throw new Error(
      `figma/brands.json lists ${key}, brand-overrides.css lacks it`
    )
  }
}
const camel = (key) => key.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())
// Runtime brand values are single-line CSS; drop the formatter's line breaks.
const flat = (value) =>
  value.replace(/\s+/g, " ").replace(/\(\s/g, "(").replace(/\s\)/g, ")")
const record = (entries) =>
  `{\n${[...entries].map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(flat(value))},`).join("\n")}\n}`
const generated =
  "/* Generated by scripts/validate-token-scopes.js --write. Do not hand edit. */\n"
const builtInSource = `${generated}/* The kit's Figma brands (figma/brands.json) as runtime brand data, with the
 * same tokens their compiled CSS sets. Extend one with extendBrand(). */
import type { BrandDefinition } from "./theme-config"

${brandList
  .map(
    ({ key, label, modes }) =>
      `export const ${camel(key)}Brand: BrandDefinition = {
  key: ${JSON.stringify(key)},
  label: ${JSON.stringify(label)},
  modes: ${JSON.stringify(modes)},
  tokens: ${record(builtInTokens.get(brandSelector(key))).replaceAll("\n", "\n  ")},
}`
  )
  .join("\n\n")}

export const builtInBrands: readonly BrandDefinition[] = [
${brandList.map(({ key }) => `  ${camel(key)}Brand,`).join("\n")}
]
`
const foundation = new Map(aliases)
for (const [name, value] of corrections) {
  foundation.set(name, value)
}
const foundationSource = `${generated}/* Every token of the shared foundation with its value, the universe a brand
 * may override. Server-side validation data; do not import it in the browser. */
export const foundationTokens: Readonly<Record<string, string>> = ${record(
  [...foundation].sort(([a], [b]) => (a < b ? -1 : 1))
)}
`
// Biome formats checked-in CSS. Compare syntax rather than whitespace. The
// generated TypeScript is excluded from Biome, so it compares exactly.
const sources = [
  [builtInOutput, builtInSource],
  [foundationOutput, foundationSource],
]
const normalize = (css) =>
  postcss
    .parse(css)
    .toString()
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, "")
if (process.argv.includes("--write")) {
  if (existsSync(output)) {
    readFileSync(output, "utf8")
  }
  writeFileSync(output, result)
  for (const [file, source] of sources) {
    writeFileSync(file, source)
  }
  console.log(`Wrote scheme scopes and brand data (${aliases.size} tokens).`)
} else if (
  normalize(readFileSync(output, "utf8")) === normalize(result) &&
  sources.every(
    ([file, source]) =>
      existsSync(file) && readFileSync(file, "utf8") === source
  )
) {
  console.log("Scheme alias scopes and brand data are up to date.")
} else {
  console.error(
    "Scheme scopes or brand data are stale. Run node scripts/validate-token-scopes.js --write."
  )
  process.exitCode = 1
}
