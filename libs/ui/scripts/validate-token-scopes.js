#!/usr/bin/env node
/* Re-resolve aliases at scheme boundaries, rather than inheriting computed
 * root snapshots. Run with --write after changing token aliases. */
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import postcss from "postcss"

const root = fileURLToPath(new URL("../src/tokens/", import.meta.url))
const output = path.join(root, "_scheme-scopes.css")
const IMPORT_PATH = /^["'](\.[^"']+)["']/
const DYNAMIC_VALUE = /var\(|light-dark\(/
const aliases = new Map()
const visited = new Set()
function collect(file) {
  if (visited.has(file) || file === output) {
    return
  }
  visited.add(file)
  const css = postcss.parse(readFileSync(file, "utf8"))
  css.each((node) => {
    if (node.type === "atrule" && node.name === "import") {
      const relative = node.params.match(IMPORT_PATH)?.[1]
      if (relative) {
        collect(path.resolve(path.dirname(file), relative))
      }
    }
    if (node.type === "atrule" && node.name === "theme") {
      node.walkDecls((decl) => aliases.set(decl.prop, decl.value))
    }
  })
}
collect(path.join(root, "_tokens-base.css"))
const scopes =
  ":where(:root, .light, .dark, .always-light, .always-dark, .reverse, [data-theme])"
const declarations = (entries) =>
  [...entries]
    .filter(([, value]) => DYNAMIC_VALUE.test(value))
    .map(([name, value]) => `    ${name}: ${value};`)
    .join("\n")
const corrections = new Map()
const brandCorrections = new Map()
postcss
  .parse(readFileSync(path.join(root, "_foundation-overrides.css"), "utf8"))
  .walkDecls((decl) => {
    const selector = decl.parent.selector
    if (selector?.startsWith("[data-theme=")) {
      const entries = brandCorrections.get(selector) ?? new Map()
      entries.set(decl.prop, decl.value)
      brandCorrections.set(selector, entries)
    } else {
      corrections.set(decl.prop, decl.value)
    }
  })
const brands = postcss.parse(
  readFileSync(path.join(root, "figma/brand-overrides.css"), "utf8")
)
let result = `/* Generated by scripts/validate-token-scopes.js --write. Do not hand edit.\n * Aliases resolve in each scheme/brand scope; literals remain inherited. */\n@layer theme {\n  ${scopes} {\n${declarations(aliases)}\n  }\n`
brands.walkRules((rule) => {
  if (!rule.selector.startsWith("[data-theme=")) {
    return
  }
  const entries = new Map()
  rule.walkDecls((decl) => {
    if (!corrections.has(decl.prop)) {
      entries.set(decl.prop, decl.value)
    }
  })
  for (const [name, value] of brandCorrections.get(rule.selector) ?? []) {
    entries.set(name, value)
  }
  // Scope proximity, not distant ancestor selector order, chooses the brand.
  result += `  @scope (${rule.selector}) to ([data-theme]) {\n    :where(:scope, .light, .dark, .always-light, .always-dark, .reverse) {\n${declarations(entries)}\n    }\n  }\n`
})
result += "}\n"
// Biome formats checked-in CSS. Compare syntax rather than whitespace.
const normalize = (css) =>
  postcss
    .parse(css)
    .toString()
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, "")
if (process.argv.includes("--write")) {
  if (existsSync(output)) {
    readFileSync(output, "utf8")
  }
  writeFileSync(output, result)
  console.log(`Wrote scheme scopes (${aliases.size} tokens).`)
} else if (normalize(readFileSync(output, "utf8")) === normalize(result)) {
  console.log("Scheme alias scopes are up to date.")
} else {
  console.error(
    "Scheme scopes are stale. Run node scripts/validate-token-scopes.js --write."
  )
  process.exitCode = 1
}
